# Doc card helper
# =========================================================
def doc_card(title, items, sheet_name):
    ws = wb.create_sheet(sheet_name)
    ws.sheet_view.showGridLines = False
    set_title(ws, 1, 1, 3, title)
    r = 3
    for kind, *args in items:
        if kind == "h2":
            set_h2(ws, r, 1, 3, args[0]); r += 1
        elif kind == "kv":
            k, v = args
            ws.cell(r,1,k).alignment = LEFT; ws.cell(r,1).font = BOLD
            cv = ws.cell(r,2,v); cv.alignment = LEFT
            ws.merge_cells(start_row=r,end_row=r,start_column=2,end_column=3)
            for j in (1,2): ws.cell(r,j).border = BORDER
            r += 1
        elif kind == "num":
            k, v = args
            ws.cell(r,1,k).alignment = LEFT; ws.cell(r,1).font = BOLD
            ws.cell(r,2,v).number_format = NUM_FORMAT
            for j in (1,2,3): ws.cell(r,j).border = BORDER
            r += 1
        elif kind == "table":
            headers, rows = args
            for j,h in enumerate(headers):
                c = ws.cell(r,1+j,h); styled(c, font=BOLD, fill=SUB_FILL, align=CENTER)
            r += 1
            for row in rows:
                for j,v in enumerate(row):
                    cc = ws.cell(r,1+j,v)
                    styled(cc, align=LEFT)
                    if isinstance(v, (int,float)) and j>0:
                        cc.number_format = NUM_FORMAT
                r += 1
        elif kind == "note":
            ws.merge_cells(start_row=r,end_row=r,start_column=1,end_column=3)
            c = ws.cell(r,1,args[0]); c.alignment = WRAP
            c.font = Font(italic=True, color="555555")
            r += 1
        elif kind == "gap":
            r += 1
    ws.column_dimensions["A"].width = 36
    ws.column_dimensions["B"].width = 24
    ws.column_dimensions["C"].width = 56
    ws.freeze_panes = "A3"
    return ws


