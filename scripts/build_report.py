def styled(cell, *, font=None, fill=None, align=None, fmt=None, border=BORDER):
    if font: cell.font = font
    if fill: cell.fill = fill
    if align: cell.alignment = align
    if fmt: cell.number_format = fmt
    if border: cell.border = border


def autosize(ws, max_w=70):
    widths = {}
    for row in ws.iter_rows():
        for c in row:
            if c.value is None: continue
            l = max(len(s) for s in str(c.value).split("\n"))
            widths[c.column_letter] = max(widths.get(c.column_letter,8), min(l+2, max_w))
    for col,w in widths.items():
        ws.column_dimensions[col].width = w


def set_title(ws, row, col, span, text, font=TITLE_FONT, fill=TITLE_FILL, height=28):
    ws.merge_cells(start_row=row, end_row=row, start_column=col, end_column=col+span-1)
    c = ws.cell(row, col); c.value = text
    styled(c, font=font, fill=fill, align=CENTER, border=None)
    ws.row_dimensions[row].height = height


